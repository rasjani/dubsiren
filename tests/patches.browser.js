async function patchPersistenceChecks(page) {
  const url=page.url(), context=await page.context().browser().newContext();
  page=await context.newPage(); await page.goto(url);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const check=(ok,label)=>{if(!ok)throw new Error(label);};
  const ready=()=>page.waitForFunction(()=>!!window.ZongoDubSiren && !!document.querySelector('#midiRows tr'));
  const value=name=>page.locator('input.'+name).inputValue();
  const edit=(name,value)=>page.locator('input.'+name).evaluate((input,value)=>{input.value=value;input.dispatchEvent(new Event('input',{bubbles:true}));input.dispatchEvent(new Event('change',{bubbles:true}));},value);
  await ready();await edit('mainFrequency','655');await edit('volume','0.23');
  await page.locator('.modulationTapTempoSync').check(); await page.locator('.delayTapTempoSync').check();
  await page.locator('input.mainOscillatorType[value="sine"]').check();
  await page.locator('input.delayFactor[value="0.5"]').check();
  await page.reload();await ready();
  check(await value('mainFrequency')==='655','Default patch edits survive without explicit patch selection');
  check(await value('volume')==='0.23','Global volume survives reload');
  check(await page.locator('.modulationTapTempoSync').isChecked(),'Sync checkbox persists');
  check(await page.locator('input.mainOscillatorType[value="sine"]').isChecked(),'Waveform persists');
  check(await page.locator('input.delayFactor[value="0.5"]').isChecked(),'Delay factor persists');
  await page.locator('input[name=patch][value="2"]').check();
  check(await value('mainFrequency')==='660','Patch two has independent defaults');
  check(await value('volume')==='0.23','Switching patch preserves global volume');
  await edit('mainFrequency','800');await edit('volume','0.42');
  await page.locator('input[name=patch][value="1"]').check();
  check(await value('mainFrequency')==='655','Patch one retains its values');
  check(await value('volume')==='0.42','Volume independent of both patches');
  const original=await value('modulationFrequency');
  await page.locator('#tapTempoButton').click(); await page.waitForTimeout(510);await page.locator('#tapTempoButton').click();
  check(await value('modulationFrequency')!==original,'Tap changes runtime LFO frequency');
  await edit('delayFeedback','0.61');
  await page.reload(); await ready();
  check(await value('modulationFrequency')===original,'Saving another control does not persist tapped runtime frequency');
  check((await page.locator('#tapTempoValue').textContent()).trim()==='---','BPM not restored');
  check(await value('delayFeedback')==='0.61','Other edits survive after tapping');
  check(await value('volume')==='0.42','Latest global volume restored');
  await page.locator('.modulationTapTempoSync').uncheck();await page.reload();await ready();
  check(!(await page.locator('.modulationTapTempoSync').isChecked()),'Checkbox changes persist across subsequent restarts');
  const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('dubsiren:settings:v2')));
  check(!Object.hasOwn(stored.patches['1'],'volume'),'Patch contains no volume');
  check(!JSON.stringify(stored).includes('BPM'),'No stored BPM');
  check(errors.length===0,errors.join('\n'));
  await context.close();return {checks:'default patch, patch isolation, global volume, waveforms, delay factor, checkboxes, runtime-only tempo',errors};
}
